package utils

import (
	"path/filepath"
	"strings"
)

var supportedExtensions = [...]string{
	// Images
	".jpg",
	".png",
	".webp",

	// Raw images
	".crw",
	".cr2",
	".cr3",
	".nef",
	".nrw",
	".orf",
	".raw",
	".rw2",
	".arw",
	".srf",
	".sr2",
	".raf",
	".dng",

	// Videos
	".mpg",
	".mod",
	".mmv",
	".tod",
	".wmv",
	".asf",
	".avi",
	".divx",
	".mov",
	".m4v",
	".3gp",
	".3g2",
	".mp4",
	".m2t",
	".m2ts",
	".mts",
	".mkv",
}

// The comparison is case-insensitive (e.g. ".JPG" or ".MOV" from cameras and phones)
func isExtensionSupported(toCheck string) bool {
	toCheck = strings.ToLower(toCheck)
	for _, extension := range supportedExtensions {
		if toCheck == extension {
			return true
		}
	}
	return false
}

// Directories which only contain files generated by a NAS (thumbnails, indexes...) and must not be uploaded
var ignoredDirectories = [...]string{
	"@eaDir", // Synology
}

// IsIgnoredPath returns true if any element of the given path is an ignored directory
func IsIgnoredPath(path string) bool {
	for _, element := range strings.Split(filepath.ToSlash(path), "/") {
		for _, ignored := range ignoredDirectories {
			if element == ignored {
				return true
			}
		}
	}
	return false
}
